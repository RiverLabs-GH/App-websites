// Prepares the website's assets from the EverOn product repo and from the captures in captures/.
// Outputs are committed (src/styles/app-tokens.css, public/brand, public/favicon, public/images), so CI does not need the product repo.
//   EVERON_REPO  product repo (default /Users/vipinkp/PycharmProjects/EverOn). Read only.
// Run: npm run assets
import { readFile, writeFile, copyFile, mkdir, readdir } from 'node:fs/promises'
import { existsSync } from 'node:fs'
import path from 'node:path'
import sharp from 'sharp'

const repo = process.env.EVERON_REPO ?? '/Users/vipinkp/PycharmProjects/EverOn'
const root = process.cwd()
const out = (...p) => path.join(root, ...p)

// 1. App tokens, scoped so a generated screen can show any theme inside any page.
if (existsSync(path.join(repo, 'src/renderer/styles/tokens.css'))) {
  const css = await readFile(path.join(repo, 'src/renderer/styles/tokens.css'), 'utf8')
  const scoped = css
    .replace(/^:root, \[data-theme="light"\]/m, '.ev-app, .ev-app[data-theme="light"]')
    .replace(/^\[data-theme="([a-z]+)"\](\[data-accent="[a-z]+"\])?/gm, (_, t, a = '') => `.ev-app[data-theme="${t}"]${a}`)
    .replace(/^:root \{/m, '.ev-app {')
    .replace(/@media \(prefers-contrast: more\) \{[\s\S]*?\n\}\n?$/m, '')
  await writeFile(out('src/styles/app-tokens.css'), `/* Generated by tools/prepare-assets.mjs from ${'EverOn'} src/renderer/styles/tokens.css. Do not edit. Scoped to .ev-app so it never touches the site's own tokens. */\n${scoped}`)
  console.log('app-tokens.css written')
} else console.log(`no product repo at ${repo}: kept the committed app-tokens.css`)

// 2. Tray marks (brand marks).
const states = ['Active', 'Inactive', 'Paused', 'Attention', 'Unknown']
await mkdir(out('public/brand'), { recursive: true })
if (existsSync(path.join(repo, 'assets/icons/trayActiveTemplate@2x.png'))) {
  for (const s of states) await copyFile(path.join(repo, `assets/icons/tray${s}Template@2x.png`), out(`public/brand/tray-${s.toLowerCase()}.png`))
  console.log('tray marks copied')
}

// 3. Favicon, touch icon and OG image from the real tray ring (white mark on the EverOn accent).
const ring = out('public/brand/tray-active.png')
if (existsSync(ring)) {
  const mark = async (size) => {
    const alpha = await sharp(ring).resize(size, size, { kernel: 'lanczos3' }).ensureAlpha().extractChannel(3).toBuffer()
    return sharp({ create: { width: size, height: size, channels: 3, background: '#ffffff' } }).joinChannel(alpha).png().toBuffer()
  }
  const tile = async (size, radius) => sharp(Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}"><rect width="${size}" height="${size}" rx="${radius}" fill="#2457c5"/></svg>`))
    .composite([{ input: await mark(Math.round(size * 0.62)), gravity: 'center' }]).png().toBuffer()
  await mkdir(out('public/favicon'), { recursive: true })
  await writeFile(out('public/favicon/favicon-32.png'), await tile(32, 7))
  await writeFile(out('public/favicon/apple-touch-icon.png'), await tile(180, 0))
  await writeFile(out('public/favicon/icon-512.png'), await tile(512, 112))
  const bg = Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="630"><defs><radialGradient id="g" cx="18%" cy="0%" r="90%"><stop offset="0" stop-color="#3c6ad8"/><stop offset="1" stop-color="#1b2a55"/></radialGradient></defs><rect width="1200" height="630" fill="url(#g)"/>
<text x="80" y="300" font-family="Helvetica, Arial, sans-serif" font-size="64" font-weight="700" fill="#fff">Keep your Mac awake for</text>
<text x="80" y="380" font-family="Helvetica, Arial, sans-serif" font-size="64" font-weight="700" fill="#fff">long AI coding runs.</text>
<text x="80" y="450" font-family="Helvetica, Arial, sans-serif" font-size="30" fill="#c9d6f7">Limits you set. A reason you can read.</text>
<text x="156" y="556" font-family="Helvetica, Arial, sans-serif" font-size="34" font-weight="600" fill="#fff">EverOn</text></svg>`)
  await sharp(bg).composite([{ input: await mark(56), left: 80, top: 520 }]).jpeg({ quality: 88 }).toFile(out('public/images/og-image.jpg'))
  console.log('favicon and OG image written')
}

// 4. Captures to WebP, with sizes recorded for width/height attributes. The restricted ones (see captures/manifest.json claimsNote) are skipped.
const dir = out('captures')
if (existsSync(path.join(dir, 'manifest.json'))) {
  const manifest = JSON.parse(await readFile(path.join(dir, 'manifest.json'), 'utf8'))
  const used = manifest.items.filter((i) => !i.claimsNote && !/^settings-(general|automation|notifications)$/.test(i.id))
  await mkdir(out('public/images/app'), { recursive: true })
  const index = {}
  for (const it of used) {
    const src = path.join(dir, it.file)
    if (!existsSync(src)) continue
    const width = it.target === 'window' ? 1760 : 640
    const info = await sharp(src).resize({ width, withoutEnlargement: true }).webp({ quality: it.target === 'window' ? 80 : 86 }).toFile(out(`public/images/app/${it.id}-${it.theme}.webp`))
    index[`${it.id}-${it.theme}`] = { w: info.width, h: info.height, state: it.state, note: it.note, target: it.target }
  }
  await writeFile(out('src/data/images.json'), JSON.stringify(index, null, 2) + '\n')
  console.log(`${Object.keys(index).length} captures converted`)
}
